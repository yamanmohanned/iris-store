#!/usr/bin/env node
/**
 * Stitch → React converter.
 *
 * Reads the exported Stitch screens in design/stitch/ (html + manifest + images map)
 * and produces TSX components.
 *
 * Usage:
 *   node scripts/stitch/convert.mjs raw   [--out src/_raw] [id-prefix ...]
 *   node scripts/stitch/convert.mjs build [--force] [--only] [id-prefix ...]
 *
 * raw    converts every <body> verbatim (including the page's own header / footer / aside) so the
 *        converter can be validated pixel-for-pixel against the original HTML.
 * build  converts each screen listed in pages.config.mjs into src/pages/<out>.tsx, stripping the shell
 *        (header / footer / sidebar / tab-bar) that is provided by shared layouts, rewriting links to
 *        react-router <Link>, and formatting the result with prettier.
 *        Existing files are NEVER overwritten unless --force is passed (pages are hand-curated afterwards).
 */
import fs from 'node:fs';
import path from 'node:path';
import { pathToFileURL } from 'node:url';
import * as cheerio from 'cheerio';
import prettier from 'prettier';
import { applyBindings } from './bindings.mjs';
import { collectText, jsStr, serializeChildren } from './jsx.mjs';

const ROOT = path.resolve(import.meta.dirname, '../..');
const DESIGN = path.join(ROOT, 'design/stitch');

export function loadManifest() {
  return JSON.parse(fs.readFileSync(path.join(DESIGN, 'manifest.json'), 'utf8')).filter((m) => m.html && m.html.endsWith('.html'));
}

export function loadImageMap() {
  return JSON.parse(fs.readFileSync(path.join(DESIGN, 'images.json'), 'utf8'));
}

const URL_RE = /https:\/\/lh3\.googleusercontent\.com\/[^\s"'()<>\\]+/g;

export function makeRewriter(imageMap) {
  return (str) => str.replace(URL_RE, (u) => imageMap[u] ?? u);
}

const NOISE_TAGS = new Set(['script', 'style', 'meta', 'link', 'title', 'noscript', 'base']);

/** Top-level body children that carry real content (drops head-ish elements that exporting moved into <body>). */
export function bodyContentNodes($) {
  return $('body')
    .contents()
    .toArray()
    .filter((n) => {
      if (n.type === 'comment') return false;
      if (n.type === 'text') return (n.data || '').trim() !== '';
      if (n.type !== 'tag') return false;
      if (NOISE_TAGS.has(n.name)) return false;
      if (n.name === 'svg' && /inline-defs-container/.test(n.attribs?.class || '')) return false;
      return true;
    });
}

export function pageInfo(html) {
  const usesForms = /cdn\.tailwindcss\.com\?plugins=[^"']*forms/.test(html);
  return { usesForms };
}

export function createCtx(imageMap, report, extra = {}) {
  const rewriteUrls = makeRewriter(imageMap);
  return {
    rewriteUrls,
    report,
    usedComponents: new Set(),
    imgSrc(value, attribs) {
      // the design used jewellery photos as "Profile" avatars – use a neutral avatar instead
      if ((attribs.alt || '').trim().toLowerCase() === 'profile') return '/images/avatar-default.svg';
      return value;
    },
    ...extra,
  };
}

/* ───────────────────────── raw mode ───────────────────────── */

function rawComponent(m, html, imageMap) {
  const $ = cheerio.load(html);
  const report = { handlers: [], hrefs: [], images: new Set() };
  const ctx = createCtx(imageMap, report, { dropRoutingAttrs: false });
  const nodes = bodyContentNodes($);
  const holder = { children: nodes };
  const inner = serializeChildren(holder, ctx);
  const bodyClass = ($('body').attr('class') || '').replace(/\s+/g, ' ').trim();
  const { usesForms } = pageInfo(html);
  const cls = [bodyClass, usesForms ? 'tw-forms' : ''].filter(Boolean).join(' ');
  const src = `// Auto-generated by scripts/stitch/convert.mjs (raw) — Stitch screen ${m.id}
// ${(m.title || '').replace(/\*\//g, '')}
export default function Screen() {
  return (
    <div className=${jsStr(cls)}>
      ${inner}
    </div>
  );
}
`;
  return { src, report };
}

function runRaw(args) {
  let outDir = path.join(ROOT, 'src/_raw');
  const prefixes = [];
  for (let i = 0; i < args.length; i++) {
    if (args[i] === '--out') outDir = path.resolve(args[++i]);
    else prefixes.push(args[i]);
  }
  fs.mkdirSync(outDir, { recursive: true });
  const imageMap = loadImageMap();
  const manifest = loadManifest().filter((m) => prefixes.length === 0 || prefixes.some((p) => m.id.startsWith(p)));

  const index = [];
  const allHandlers = {};
  for (const m of manifest) {
    const html = fs.readFileSync(path.join(DESIGN, m.html), 'utf8');
    const { src, report } = rawComponent(m, html, imageMap);
    fs.writeFileSync(path.join(outDir, `${m.id}.tsx`), src);
    index.push({ id: m.id, title: m.title, width: m.width });
    if (report.handlers.length) allHandlers[m.id] = report.handlers;
  }
  const lines = [
    '// Auto-generated by scripts/stitch/convert.mjs (raw)',
    'import type { ComponentType } from "react";',
    '',
    'export interface RawScreen { id: string; title: string; width: number; load: () => Promise<{ default: ComponentType }>; }',
    'export const rawScreens: RawScreen[] = [',
    ...index.map((s) => `  { id: ${jsStr(s.id)}, title: ${jsStr(s.title || '')}, width: ${s.width}, load: () => import(${jsStr('./' + s.id)}) },`),
    '];',
    '',
  ];
  fs.writeFileSync(path.join(outDir, 'index.ts'), lines.join('\n'));
  fs.writeFileSync(path.join(outDir, '_handlers.json'), JSON.stringify(allHandlers, null, 1));
  console.log(`raw: converted ${manifest.length} screens -> ${path.relative(ROOT, outDir)}`);
}

/* ───────────────────────── build mode ───────────────────────── */

const STORE_STRIP = [
  'body > header',
  'body > footer',
  'body > aside',
  'body > #scroll-progress-bar',
  'body > #header-announcement',
  'body > #cart-drawer-container',
  'body > div.fixed.top-0.h-0\\.5', // thin top progress bars on content pages
];

const WRAPPER_NOISE = new Set(['antialiased', 'font-body-md', 'font-body', 'text-body-md', 'font-sans']);

const CATEGORY_TEXT = {
  القلائد: '/collections/necklaces',
  الخواتم: '/collections/rings',
  الأساور: '/collections/bracelets',
  الأقراط: '/collections/earrings',
  الهدايا: '/collections/gifts',
  'مجموعات الهدايا': '/collections/gifts',
  العروض: '/collections/offers',
};

const LABEL_ROUTES_STORE = [
  [/^(الرئيسية|العودة (إلى|للـ?) ?الرئيسية|العودة للمتجر)$/, '/'],
  [/(إتمام الطلب|إتمام الشراء|المتابعة إلى الدفع|إتمام عملية الشراء)/, '/checkout'],
  [/^(عرض السلة|السلة|السلة الملكية|حقيبة التسوق|حقيبة المقتنيات)$/, '/cart'],
  [/(متابعة التسوق|مواصلة التسوق|استكشاف المجموعات|تصفح المجموعات|تصفّح المجموعات|تصفّحي المجموعات|العودة إلى المتجر)/, '/collections/necklaces'],
  [/(تتبع (طلبي|الطلب|مسار|الشحنة)|تتبّع)/, '/track-order'],
  [/(سجل الطلبات|طلباتي|الطلبات السابقة)/, '/account/orders'],
  [/(تسجيل الدخول|تسجيل دخول)/, '/login'],
  [/(طلب (إرجاع|استبدال)|الإرجاع والاستبدال)/, '/returns/new'],
  [/(تواصل معنا|تواصل مباشر|اتصل بنا)/, '/contact'],
  [/^الأسئلة الشائعة$/, '/faq'],
  [/(عن المتجر|حكاية الدار|قصتنا)/, '/about'],
];

const LABEL_ROUTES_ADMIN = [
  [/(إنشاء طلب جديد|طلب جديد)$/, '/admin/orders/new'],
  [/(إضافة منتج|منتج جديد)/, '/admin/products/new'],
  [/(أمر شراء جديد|شراء جديد|استلام بضاعة)/, '/admin/purchases/new'],
  [/^(عرض كل الطلبات|كافة الطلبات)$/, '/admin/orders'],
];

function norm(s) {
  return s.replace(/[ً-ٰٟ]/g, '').replace(/\s+/g, ' ').trim();
}

function makeLinkMapper({ shell, routeMap, products }) {
  const admin = shell === 'admin';
  const table = admin ? routeMap.admin : routeMap.store;
  const labels = admin ? LABEL_ROUTES_ADMIN : LABEL_ROUTES_STORE;
  const productKeys = products.flatMap((p) => [p.shortName, p.name].map((n) => [norm(n), p]));

  return (node) => {
    const a = node.attribs || {};
    const href = (a.href ?? '').trim();
    if (/^(tel:|mailto:|sms:)/.test(href)) return { external: true };
    if (/^https?:\/\//.test(href)) return { external: true, blank: true };
    if (href.startsWith('/')) return { to: href };
    const dp = a['data-path'];
    if (dp && table[dp]) return { to: table[dp] };
    const text = norm(collectText(node));
    const label = norm(a['aria-label'] ?? '');
    if (!admin) {
      const hit = productKeys.find(([k]) => k.length >= 8 && (text.includes(k) || label.includes(k)));
      if (hit) return { to: `/products/${hit[1].slug}` };
      if (CATEGORY_TEXT[text]) return { to: CATEGORY_TEXT[text] };
    }
    if (text.length <= 60) {
      for (const [re, to] of labels) if (re.test(text) || re.test(label)) return { to };
    }
    return null;
  };
}

function stripMainTopPadding($, shell) {
  if (shell !== 'store') return;
  $('main')
    .first()
    .each((_, el) => {
      const cls = (el.attribs.class || '').split(/\s+/).filter((t) => !/^pt-(16|20|24|\[\d+px\])$/.test(t));
      el.attribs.class = cls.join(' ');
    });
}

function stripAdminOffsets($) {
  for (const el of bodyContentNodes($)) {
    if (el.type !== 'tag') continue;
    const cls = (el.attribs.class || '')
      .split(/\s+/)
      .filter((t) => !/^(pr|mr)-(72|64|\d+|\[\d+px\])$/.test(t))
      .join(' ');
    el.attribs.class = cls;
  }
}

function wrapperClassFor(shell, bodyClass, usesForms) {
  if (shell === 'admin' || shell === 'store') {
    const interesting = bodyClass
      .split(/\s+/)
      .filter(Boolean)
      .filter((t) => !WRAPPER_NOISE.has(t) && !/^(bg-(surface|ivory-canvas|background)|text-on-surface|relative|min-h-screen|flex|flex-col)$/.test(t) && !t.startsWith('selection:'));
    if (!interesting.length && !usesForms) return '';
    return [...interesting, usesForms ? 'tw-forms' : ''].filter(Boolean).join(' ');
  }
  const keep = bodyClass
    .split(/\s+/)
    .filter(Boolean)
    .filter((t) => !WRAPPER_NOISE.has(t));
  return [...keep, usesForms ? 'tw-forms' : ''].filter(Boolean).join(' ');
}

async function formatTsx(src) {
  return prettier.format(src, {
    parser: 'typescript',
    singleQuote: true,
    printWidth: 140,
    trailingComma: 'all',
    semi: true,
  });
}

function titleOf(m) {
  return (m.title || '').replace(/\*\//g, '').replace(/\s+/g, ' ');
}

async function buildPage(cfg, m, ctxBase) {
  const html = fs.readFileSync(path.join(DESIGN, m.html), 'utf8');
  const $ = cheerio.load(html);
  const { usesForms } = pageInfo(html);
  const shell = cfg.shell;

  if (shell === 'store') STORE_STRIP.forEach((sel) => $(sel).remove());
  if (shell === 'mobile-tabs') $('body > nav').remove();
  if (shell === 'admin') {
    $('body > aside').remove();
    $('body > div > aside').remove();
    stripAdminOffsets($);
  }
  for (const sel of cfg.strip ?? []) $(sel).remove();
  stripMainTopPadding($, shell);
  if (cfg.bind?.length) applyBindings($, cfg.bind, cfg.out);

  const report = { handlers: [], hrefs: [], images: new Set() };
  const ctx = createCtx(ctxBase.imageMap, report, {
    mapLink: makeLinkMapper({ shell, routeMap: ctxBase.routeMap, products: ctxBase.products }),
  });
  // `contentOf` → only the children of that element (used to compose multi-part pages such as the home page)
  const holder = {
    children: cfg.contentOf
      ? $(cfg.contentOf)
          .first()
          .contents()
          .toArray()
          .filter((n) => n.type !== 'comment' && !(n.type === 'text' && !(n.data || '').trim()))
      : bodyContentNodes($),
  };
  let inner = serializeChildren(holder, ctx);
  if (/<Link[\s>]/.test(inner)) ctx.usedComponents.add('Link');

  const bodyClass = ($('body').attr('class') || '').replace(/\s+/g, ' ').trim();
  const wrapper = wrapperClassFor(shell, bodyClass, usesForms);
  const name = path.basename(cfg.out);

  const imports = [...(cfg.imports ?? [])];
  if (ctx.usedComponents.has('Link') && !imports.some((l) => /Link.*react-router/.test(l))) imports.unshift("import { Link } from 'react-router';");
  let tail = '';
  if (shell === 'mobile-tabs') {
    imports.push("import { MobileTabBar } from '@/components/mobile/MobileTabBar';");
    tail = `<MobileTabBar active=${jsStr(cfg.tab ?? 'home')} />`;
  }

  const body = wrapper && !cfg.contentOf ? `<div className=${jsStr(wrapper)}>${inner}${tail}</div>` : `<>${inner}${tail}</>`;
  const src = `${imports.join('\n')}${imports.length ? '\n\n' : ''}/**
 * Stitch screen ${m.id}
 * «${titleOf(m)}»
 * Generated by scripts/stitch/convert.mjs${cfg.bind?.length ? ' with data bindings — change the bindings in scripts/stitch/pages.config.mjs, not this file' : ' — hand-curated afterwards'}.
 */
export default function ${name}() {
${cfg.hooks ?? ''}
${cfg.guard ?? ''}
  return (${body});
}
`;
  return { src: await formatTsx(src), report };
}

async function runBuild(args) {
  const force = args.includes('--force');
  const prefixes = args.filter((a) => !a.startsWith('--'));
  const { pages } = await import(pathToFileURL(path.join(import.meta.dirname, 'pages.config.mjs')).href);
  const routeMap = JSON.parse(fs.readFileSync(path.join(import.meta.dirname, 'route-map.json'), 'utf8'));
  const { products } = await import(pathToFileURL(path.join(ROOT, 'src/data/catalog.ts')).href);
  const imageMap = loadImageMap();
  const manifest = loadManifest();
  const ctxBase = { imageMap, routeMap, products };

  let written = 0;
  let skipped = 0;
  let existing = 0;
  const handlerReport = {};
  for (const cfg of pages) {
    if (prefixes.length && !prefixes.some((p) => cfg.id.startsWith(p))) continue;
    if (cfg.shell === 'skip') {
      skipped++;
      continue;
    }
    const m = manifest.find((x) => x.id.startsWith(cfg.id));
    if (!m) {
      console.error('!! no screen for', cfg.id);
      continue;
    }
    const outFile = path.join(ROOT, 'src/pages', `${cfg.out}.tsx`);
    if (fs.existsSync(outFile) && !force) {
      existing++;
      continue;
    }
    const { src, report } = await buildPage(cfg, m, ctxBase);
    fs.mkdirSync(path.dirname(outFile), { recursive: true });
    fs.writeFileSync(outFile, src);
    written++;
    if (report.handlers.length) handlerReport[cfg.out] = report.handlers.map((h) => `${h.event}: ${h.code}`);
  }
  fs.writeFileSync(path.join(ROOT, 'scripts/stitch/.handlers.json'), JSON.stringify(handlerReport, null, 1));
  console.log(`build: wrote ${written}, kept ${existing} existing, skipped ${skipped} frames`);
  console.log(`pages with inline handlers to port: ${Object.keys(handlerReport).length} (scripts/stitch/.handlers.json)`);
}

async function main() {
  const [mode, ...rest] = process.argv.slice(2);
  if (mode === 'raw') return runRaw(rest);
  if (mode === 'build') return runBuild(rest);
  console.error('usage: convert.mjs raw|build [options]');
  process.exit(1);
}

if (process.argv[1] && path.resolve(process.argv[1]) === path.resolve(import.meta.filename)) await main();
